import type { QuestionType } from "./grading";
export type QuestionSeed = {
  id: string;
  subject: string;
  topic: string;
  type: QuestionType;
  prompt: string;
  options?: string[];
  answer: string | string[];
  explanation: string;
  hint: string;
  difficulty: "Easy" | "Medium" | "Hard";
  unit?: string;
  tolerance?: number;
  examTags: string[];
  version: number;
  source: string;
  reviewStatus: string;
};
type Input = Omit<
  QuestionSeed,
  "id" | "version" | "source" | "reviewStatus" | "examTags" | "difficulty"
> & { difficulty?: QuestionSeed["difficulty"]; examTags?: string[] };
let seq = 0;
const q = (x: Input): QuestionSeed => ({
  ...x,
  id: `original-${String(++seq).padStart(3, "0")}`,
  difficulty: x.difficulty ?? "Easy",
  examTags:
    x.examTags ??
    (["Physics", "Chemistry"].includes(x.subject)
      ? ["JEE", "NEET"]
      : x.subject === "Maths"
        ? ["JEE"]
        : x.subject === "Biology"
          ? ["NEET"]
          : x.subject === "Quantitative Reasoning"
            ? ["GMAT"]
            : ["University"]),
  version: 1,
  source: "Ingenium original · synthetic demo",
  reviewStatus: "checked",
});
const num = (
  subject: string,
  topic: string,
  prompt: string,
  answer: number,
  explanation: string,
  hint: string,
  unit?: string,
  tolerance = 0.001,
): QuestionSeed =>
  q({
    subject,
    topic,
    type: "numerical",
    prompt,
    answer: String(answer),
    explanation,
    hint,
    unit,
    tolerance,
  });
const single = (
  subject: string,
  topic: string,
  prompt: string,
  options: string[],
  answer: string,
  explanation: string,
  hint: string,
): QuestionSeed =>
  q({
    subject,
    topic,
    type: "single",
    prompt,
    options,
    answer,
    explanation,
    hint,
  });
